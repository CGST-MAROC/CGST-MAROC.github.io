/* ═══════════════════════════════════════════════════
   Build Year Pills Dynamically
═══════════════════════════════════════════════════ */
function buildYearPills() {
  const years = [...new Set(exams.map(e => e.year))].sort().reverse();
  years.forEach(year => {
    const pill = document.createElement("button");
    pill.className = "pill";
    pill.dataset.year = year;
    pill.textContent = year;
    pill.addEventListener("click", () => {
      document.querySelectorAll(".pill[data-year]").forEach(p => p.classList.remove("active"));
      pill.classList.add("active");
      currentYear = year;
      renderExams();
    });
    yearPills.appendChild(pill);
  });

  const allPill = document.querySelector('.pill[data-year="all"]');
  if (allPill) {
    allPill.addEventListener("click", (e) => {
      document.querySelectorAll(".pill[data-year]").forEach(p => p.classList.remove("active"));
      e.target.classList.add("active");
      currentYear = "all";
      renderExams();
    });
  }
}

/* ═══════════════════════════════════════════════════
   Build Language Pills
═══════════════════════════════════════════════════ */
function buildLanguagePills() {
  const container = document.getElementById("languagePills");
  if (!container) return;

  const languages = [
    { value: "all",    label: "Toutes" },
    { value: "french", label: "🇫🇷 Français" },
    { value: "arabic", label: "🇲🇦 العربية" }
  ];

  languages.forEach(lang => {
    const pill = document.createElement("button");
    pill.className = "pill" + (lang.value === "all" ? " active" : "");
    pill.dataset.lang = lang.value;
    pill.textContent = lang.label;
    pill.addEventListener("click", () => {
      document.querySelectorAll(".pill[data-lang]").forEach(p => p.classList.remove("active"));
      pill.classList.add("active");
      currentLanguage = lang.value;
      renderExams();
    });
    container.appendChild(pill);
  });
}

/* ═══════════════════════════════════════════════════
   Subject Tabs & Search
═══════════════════════════════════════════════════ */
tabs.forEach(tab => {
  tab.addEventListener("click", () => {
    tabs.forEach(t => {
      t.classList.remove("active");
      t.setAttribute("aria-selected", "false");
    });
    tab.classList.add("active");
    tab.setAttribute("aria-selected", "true");
    currentSubject = tab.dataset.subject;
    renderExams();
  });
});

searchInput.addEventListener("input", (e) => {
  currentSearch = e.target.value.trim().toLowerCase();
  renderExams();
});

/* ═══════════════════════════════════════════════════
   Language badge helper
═══════════════════════════════════════════════════ */
function languageBadge(language) {
  if (language === "french") {
    return `<span class="card-lang-badge lang-french">🇫🇷 Français</span>`;
  }
  if (language === "arabic") {
    return `<span class="card-lang-badge lang-arabic">🇲🇦 العربية</span>`;
  }
  return "";
}

/* ═══════════════════════════════════════════════════
   Render Exam Cards
═══════════════════════════════════════════════════ */
function renderExams() {
  const filtered = exams.filter(e => {
    const matchSubject = e.subject === currentSubject;
    const matchYear    = currentYear === "all" || e.year === currentYear;
    const matchLang    = currentLanguage === "all" || e.language === currentLanguage;
    const matchSearch  = !currentSearch || e.title.toLowerCase().includes(currentSearch);
    return matchSubject && matchYear && matchLang && matchSearch;
  });

  examsGrid.innerHTML = "";

  if (filtered.length === 0) {
    emptyState.hidden = false;
    return;
  }
  emptyState.hidden = true;

  filtered.forEach(exam => {
    const card = document.createElement("div");
    card.className = "exam-card";
    card.dataset.subject = exam.subject;

    card.innerHTML = `
      <div class="card-header">
        <span class="card-subject-badge">${subjectLabel(exam.subject)}</span>
        <div class="card-badges-right">
          ${languageBadge(exam.language)}
          <span class="card-type-badge ${exam.type}">${exam.type === "sujet" ? "Sujet" : "Corrigé"}</span>
        </div>
      </div>
      <h3 class="card-title">${exam.title}</h3>
      <div class="card-meta">
        <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
          <rect x="3" y="4" width="18" height="18" rx="2"/><path d="M16 2v4M8 2v4M3 10h18"/>
        </svg>
        Session ${exam.year}
      </div>
      <div class="card-actions">
        <button class="btn-download btn-view"
          data-preview="${exam.previewUrl}"
          data-download="${exam.downloadUrl}"
          data-title="${exam.title}">
          <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
            <path d="M1 12s4-8 11-8 11 8 11 8-4 8-11 8-11-8-11-8z"/><circle cx="12" cy="12" r="3"/>
          </svg>
          Voir
        </button>
        <a class="btn-download secondary" href="${exam.downloadUrl}" target="_blank" rel="noopener">
          <svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
            <path d="M12 3v12m0 0l-4-4m4 4l4-4M4 21h16"/>
          </svg>
          Télécharger
        </a>
      </div>
    `;
    examsGrid.appendChild(card);
  });
}

/* ═══════════════════════════════════════════════════
   Global Event Delegation for "Voir" buttons
═══════════════════════════════════════════════════ */
examsGrid.addEventListener("click", (e) => {
  const viewBtn = e.target.closest(".btn-view");
  if (viewBtn) {
    openPdfViewer(
      viewBtn.dataset.preview,
      viewBtn.dataset.download,
      viewBtn.dataset.title
    );
  }
});

function subjectLabel(subject) {
  const map = {
    mathematiques: "Mathématiques",
    physique:      "Physique-Chimie",
    svt:           "S.V.T",
    si:            "Sciences de l'Ingénieur"
  };
  return map[subject] || subject;
}

/* ═══════════════════════════════════════════════════
   PDF Viewer Modal
═══════════════════════════════════════════════════ */
function openPdfViewer(previewUrl, downloadUrl, title) {
  pdfFrame.src                 = previewUrl;
  pdfTitle.textContent         = title;
  pdfDownload.href             = downloadUrl;
  if (pdfOpenNewTab) pdfOpenNewTab.href = previewUrl.replace("/preview", "/view");
  pdfOverlay.hidden            = false;
  document.body.style.overflow = "hidden";
}

function closePdfViewer() {
  pdfOverlay.hidden            = true;
  pdfFrame.src                 = "";
  document.body.style.overflow = "";
}

pdfClose.addEventListener("click", closePdfViewer);
pdfOverlay.addEventListener("click", (e) => {
  if (e.target === pdfOverlay) closePdfViewer();
});
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape" && !pdfOverlay.hidden) closePdfViewer();
});

